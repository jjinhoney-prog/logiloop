test('registered partner introduction can be published without exposing private fields', async ({ page, request }, testInfo) => {
  const response = await request.post('/api/partnership', { headers: {'x-forwarded-for':testInfo.project.name === 'mobile' ? '127.0.1.12' : '127.0.1.11'}, data: { consent: true, profile: {
    company: '공개 검증 물류사', name: '비공개담당자', phone: '01098765432',
    regions: [{ province: '부산', district: '강서구' }, {province:'인천',district:'영종'}, {province:'인천',district:'중구'}], services: ['보관'], temperatures: ['상온'],
    websiteUrl: '', documentUrl: '', disclosure: '업체명·서비스 공개 희망', note: '공개금지메모', centers: [],
  } } });
  expect(response.status()).toBe(201);
  const { id } = await response.json();
  await page.goto('/admin/login');
  await page.getByLabel('비밀번호').fill('test-only-password');
  await page.getByRole('button', { name: '로그인' }).click();
  await expect(page).toHaveURL('/admin');
  await page.goto(`/admin/listings/new?partner=${id}`);
  await expect(page.locator('#name')).toHaveValue('공개 검증 물류사');
  await expect(page.locator('#service')).toHaveValue('보관');
  await expect(page.locator('#lat')).toHaveValue('');
  await page.locator('#lat').fill('35.2');
  await page.locator('#lng').fill('128.9');
  await page.getByRole('button', { name: '비공개로 등록' }).click();
  await expect(page).toHaveURL(/tab=listings/);
  await page.getByRole('row').filter({ hasText: '공개 검증 물류사' }).getByRole('button', { name: '공개', exact: true }).click();
  await expect(page.getByRole('row').filter({ hasText: '공개 검증 물류사' }).getByRole('button', { name: '비공개', exact: true })).toBeVisible();
  await page.goto('/partners');
  await expect(page.getByRole('link', { name: '공개 검증 물류사', exact: true })).toBeVisible();
  await expect(page.getByRole('article',{name:'공개 검증 물류사'})).toContainText('인천 영종');
  await page.getByRole('combobox',{name:'지역',exact:true}).click();await page.getByRole('option',{name:'인천',exact:true}).click();
  await expect(page.getByRole('link',{name:'공개 검증 물류사',exact:true})).toBeVisible();
  await page.goto(`/partners/registered-partner-${id}`);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('공개 검증 물류사');
  await expect(page.locator('body')).not.toContainText('가상 예시 자료입니다');
  for (const secret of ['비공개담당자', '01098765432', '공개금지메모']) await expect(page.locator('body')).not.toContainText(secret);
  await page.goto(`/admin/listings/new?partner=${id}`);
  await expect(page).toHaveURL(`/admin/listings/registered-partner-${id}`);
});
